import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
import { webcrypto } from 'node:crypto';

const source = fs.readFileSync(new URL('../output/seeking-light/flomo-import.js', import.meta.url), 'utf8');
const sandbox = { window: {}, TextEncoder, Date, Uint8Array };
vm.runInNewContext(source, sandbox);
const api = sandbox.window.SeekingLightImport;
const clean = value => JSON.parse(JSON.stringify(value));
assert.deepEqual(clean(api.timestamp('2024-02-29 23:59:59')), { date: '2024-02-29', time: '23:59:59' });
assert.equal(api.timestamp('2025-02-29 12:00:00'), null);
assert.equal(api.timestamp('2026-13-01 12:00:00'), null);
assert.equal(api.timestamp('2026-11-07 24:00:00'), null);
assert.equal(api.timestamp('2026-11-07 12:00:60'), null);
assert.equal(api.timestamp('yesterday'), null);
assert.deepEqual(clean(api.timestamp('2026-11-07T01:02')), { date: '2026-11-07', time: '01:02:00' });
const a = { date: '2026-11-01', time: '01:02:00', text: 'TEST_ONLY_FICTION\n#life  ordinary', tags: ['life'], source: 'flomo' };
const b = { ...a, time: '01:02:01' }, c = { ...a, text: `${a.text}!` };
const planned = api.plan([a, a, b, c], [{ ...a, time: '01:02', id: 'existing' }]);
assert.equal(planned.duplicates, 2);
assert.deepEqual(clean(planned.notes), [b, c]);
const notes = await api.identify([a, b, c], webcrypto);
assert.equal(new Set(notes.map(note => note.id)).size, 3);
assert.match(notes[0].id, /^flomo-[a-f0-9]{64}$/);
assert.equal((await api.identify([a], webcrypto))[0].id, notes[0].id);
assert.equal(api.plan(notes, notes).notes.length, 0);
assert.deepEqual(clean(notes[0].tags), ['life']);
const text = value => ({ nodeType: 3, nodeValue: value });
const element = (tagName, ...childNodes) => ({ nodeType: 1, tagName, childNodes });
const tree = element('DIV', element('P', text('TEST_ONLY_FICTION & <literal>'), element('BR'), text('line two')), element('P', text('#life')), element('SCRIPT', text('do not execute')), element('IMG'), element('PRE', text('  indented\n    code')));
assert.equal(api.plainText(tree), 'TEST_ONLY_FICTION & <literal>\nline two\n\n#life\n\n  indented\n    code');
assert.equal(api.plainText(element('DIV', element('B', text('one')), text(' '), element('I', text('two')))), 'one two');
assert.equal(api.plainText(element('DIV', element('PRE', text('  first\n    second')))), '  first\n    second');
assert.throws(() => api.parseHTML('x'.repeat(api.MAX_BYTES + 1), {}), /20 MB/);
assert.ok(!/\b(fetch|XMLHttpRequest|WebSocket)\s*\(/.test(source));
console.log('Flomo import core passed: strict timestamps, exact deduplication, deterministic IDs, tags, inert text traversal and size limit. Constructed node trees only; actual HTML parsing/file upload requires browser verification.');
